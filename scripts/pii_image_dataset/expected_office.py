"""陰性Officeの文字格納面を、原稿と固定ひな形の文言に照合する。"""
import zipfile
from xml.etree import ElementTree as ET

FIXED={'資料の確認','内容を確認してください。','補足を確認してください。',
       '埋込み資料を確認してください。','資料を確認してください。',
       'Click to edit Master subtitle style','Click to edit Master text styles',
       'Click to edit Master title style','Second level','Third level','Fourth level','Fifth level','‹#›',
       '1/27/13','10/17/16'}
PROPERTIES={'Normal.dotm','Microsoft Excel','Microsoft Excel Compatible / Openpyxl 3.1.5',
            'Microsoft Macintosh PowerPoint','Microsoft Macintosh Word','SheetJS','false','true',
            'Office Theme','Slide Titles','Theme','Title','Worksheets','内容','案内',
            '12.0000','14.0000','3.1','generated by python-docx','generated using python-pptx',
            '2000-01-01T00:00:00Z','On-screen Show (4:3)','0','1','2'}


def validate(path,row):
    if row['positive'] or row['format'] not in ['DOCX','XLSX','XLSM','PPTX']:return
    original=row['text']
    with zipfile.ZipFile(path) as package:
        for name in package.namelist():
            if not name.endswith('.xml'):continue
            root=ET.fromstring(package.read(name))
            parents={child:parent for parent in root.iter() for child in parent}
            for node in root.iter():
                value=node.text or ''
                if not value.strip():continue
                tag=node.tag.rsplit('}',1)[-1]
                if name.startswith('docProps/'):
                    allowed=value in PROPERTIES or value in original
                elif tag in ['t','delText','instrText','f','definedName','v']:
                    # 共有文字列の索引は値ではない。文字列本体は別のt要素で照合。
                    parent=parents.get(node)
                    if tag=='v' and parent is not None and parent.get('t')=='s':continue
                    candidate=value
                    if tag in ['f','definedName'] and candidate.startswith('"') and candidate.endswith('"'):
                        candidate=candidate[1:-1].replace('""','"')
                    allowed=candidate in original or candidate in FIXED
                    if tag=='v' and value=='0':allowed=True # 定数文字列数式の未計算キャッシュ
                    if tag=='definedName' and node.get('name')=='_xlnm._FilterDatabase':
                        allowed=value==f'内容!$A$1:$A${max(6,len(original.splitlines()))}'
                else:continue
                if not allowed:raise ValueError('陰性Officeに期待しない文字格納面があります: '+row['path']+' '+name+' '+tag)
