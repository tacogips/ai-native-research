def detectors():
    """規則で参照する独自正規表現の一覧（重複を除く）。Workspaceの容量確認に使う。"""
    seen = []
    for clauses in RULES.values():
        for clause in clauses:
            for rx in clause['all'] + clause['not']:
                if rx not in seen:
                    seen.append(rx)
    return seen


def detect(compiled, item, text, techs):
    """1ファイル×1項目の判定。compiledは正規表現→コンパイル済みの辞書。"""
    for clause in RULES[item]:
        if clause['tech'] not in techs:
            continue
        if all(compiled[rx].search(text) for rx in clause['all']):
            if 'T3' in techs and any(compiled[rx].search(text) for rx in clause['not']):
                continue
            return clause['tech']
    return None
